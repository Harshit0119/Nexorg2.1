/**
 * Validates whether assigning a faculty member, room, or lab at a specific slot
 * causes a conflict across ANY department in the institution.
 */
export function checkSlotConflict(params: {
  facultyId: string;
  targetDepartmentId: string;
  dayOfWeek: AcademicDay;
  startTime: string; // HH:MM
  endTime: string;   // HH:MM
  roomId?: string;
  labId?: string;
  timetableSlots: TimetableSlot[];
  departments: Department[];
  facultyProfiles: FacultyProfile[];
  users: User[];
  subjects: Subject[];
  rooms: Room[];
  labs: Lab[];
  excludeSlotId?: string;
}): ClashResult[] {
  const clashes: ClashResult[] = [];

  const startMinutes = timeToMinutes(params.startTime);
  const endMinutes = timeToMinutes(params.endTime);

  const activeSlots = params.timetableSlots.filter(
    (s) => s.day_of_week === params.dayOfWeek && s.id !== params.excludeSlotId
  );

  // 1. Cross-Department Faculty Clash Detection!
  // If Rahul is assigned in CSE 10-11, he CANNOT be assigned in AIML or IT at 10-11!
  for (const slot of activeSlots) {
    if (slot.faculty_id === params.facultyId) {
      const slotStart = timeToMinutes(slot.start_time);
      const slotEnd = timeToMinutes(slot.end_time);

      // Overlap condition
      if (startMinutes < slotEnd && endMinutes > slotStart) {
        const slotDept = params.departments.find((d) => d.id === slot.department_id);
        const facultyProf = params.facultyProfiles.find((f) => f.id === params.facultyId);
        const user = params.users.find((u) => u.id === facultyProf?.user_id);
        const subject = params.subjects.find((s) => s.id === slot.subject_id);

        clashes.push({
          has_clash: true,
          type: 'FACULTY_BUSY_IN_OTHER_DEPT',
          conflicting_entity: user?.full_name || 'Faculty Member',
          department_involved: slotDept?.name || slot.department_id,
          time_window: `${slot.start_time} - ${slot.end_time} (${slot.day_of_week})`,
          message: `CRITICAL FACULTY CLASH: ${user?.full_name || 'Faculty'} is already lecturing in Department: ${
            slotDept?.code || 'Another Dept'
          } (${subject?.code || ''} ${subject?.name || ''}) from ${slot.start_time} to ${
            slot.end_time
          }. Cross-department lock prevents simultaneous double-booking.`,
        });
      }
    }
  }

  // 2. Room Double-Booking Clash
  if (params.roomId) {
    for (const slot of activeSlots) {
      if (slot.room_id === params.roomId) {
        const slotStart = timeToMinutes(slot.start_time);
        const slotEnd = timeToMinutes(slot.end_time);

        if (startMinutes < slotEnd && endMinutes > slotStart) {
          const room = params.rooms.find((r) => r.id === params.roomId);
          const dept = params.departments.find((d) => d.id === slot.department_id);
          clashes.push({
            has_clash: true,
            type: 'ROOM_DOUBLE_BOOKED',
            conflicting_entity: room?.room_number || 'Room',
            department_involved: dept?.code || 'Other Department',
            time_window: `${slot.start_time} - ${slot.end_time}`,
            message: `ROOM OCCUPIED: Room ${room?.room_number || ''} is already booked by ${
              dept?.name || 'another department'
            } from ${slot.start_time} to ${slot.end_time}.`,
          });
        }
      }
    }
  }

  // 3. Lab Double-Booking Clash
  if (params.labId) {
    for (const slot of activeSlots) {
      if (slot.lab_id === params.labId) {
        const slotStart = timeToMinutes(slot.start_time);
        const slotEnd = timeToMinutes(slot.end_time);

        if (startMinutes < slotEnd && endMinutes > slotStart) {
          const lab = params.labs.find((l) => l.id === params.labId);
          const dept = params.departments.find((d) => d.id === slot.department_id);
          clashes.push({
            has_clash: true,
            type: 'LAB_UNAVAILABLE',
            conflicting_entity: lab?.name || 'Lab',
            department_involved: dept?.code || 'Other Department',
            time_window: `${slot.start_time} - ${slot.end_time}`,
            message: `LAB OCCUPIED: ${lab?.name || 'Lab'} (${lab?.lab_number}) is in active session with ${
              dept?.code
            } from ${slot.start_time} to ${slot.end_time}.`,
          });
        }
      }
    }
  }

  return clashes;
}

export function timeToMinutes(timeStr: string): number {
  const parts = timeStr.split(':');
  const h = parseInt(parts[0], 10) || 0;
  const m = parseInt(parts[1], 10) || 0;
  return h * 60 + m;
}

export function minutesToTime(mins: number): string {
  const h = Math.floor(mins / 60);
  const m = mins % 60;
  return `${h.toString().padStart(2, '0')}:${m.toString().padStart(2, '0')}`;
}

